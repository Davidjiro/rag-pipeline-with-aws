#!/usr/bin/env bash
# verify.sh
#
# One command that proves the CDK package is correct, in layers. It never deploys and never changes AWS.
# Run it with `npm run verify` from infra/, or directly. CI runs exactly this.
#
#   1 format      prettier check
#   2 types       tsc --noEmit (strict)
#   3 unit tests  jest: security, correctness and cost properties of every stack
#   4 synth       cdk synth with the cdk-nag AwsSolutions rules (a finding is an error)
#   5 cfn-lint    every template against AWS's CloudFormation resource schemas
#   6 AWS check   `aws cloudformation validate-template` (read-only), when credentials exist
#   7 python      the application sources compile
#   8 backend     ruff lint + format check, pytest (API, ingest, contracts) with fakes for AWS
#
# A layer that cannot run (for example cfn-lint is not installed) is reported as SKIPPED, never as passed.

set -uo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT/infra" || exit 1

RESULTS=()
FAILED=0
record() { RESULTS+=("$1|$2"); [ "$2" = "FAIL" ] && FAILED=1; return 0; }
run() { # name, command...
  local name="$1"; shift
  printf '\n==> %s\n' "$name"
  if "$@"; then record "$name" PASS; else record "$name" FAIL; fi
}
skip() { printf '\n==> %s\n    skipped: %s\n' "$1" "$2"; record "$1" "SKIPPED ($2)"; }

run "1 format (prettier)" npm run --silent format:check
run "2 types (tsc strict)" npm run --silent build
run "3 unit tests (jest)" npm test --silent
rm -rf cdk.out
run "4 synth + cdk-nag AwsSolutions" npx cdk synth --quiet

# cfn-lint: PATH first, then python module
CFNLINT=()
if command -v cfn-lint >/dev/null 2>&1; then CFNLINT=(cfn-lint)
elif python3 -m cfnlint --version >/dev/null 2>&1; then CFNLINT=(python3 -m cfnlint); fi
if [ "${#CFNLINT[@]}" -gt 0 ]; then
  # W3005: CDK adds a DependsOn on roles that a GetAtt already enforces. Harmless, and generated by CDK itself.
  run "5 cfn-lint (templates vs AWS schemas)" "${CFNLINT[@]}" cdk.out/*.template.json --ignore-checks W3005
else skip "5 cfn-lint" "not installed: pip install cfn-lint"; fi

if command -v aws >/dev/null 2>&1 && aws sts get-caller-identity >/dev/null 2>&1; then
  validate() {
    local ok=0 f
    for f in cdk.out/*.template.json; do
      if [ "$(wc -c < "$f")" -gt 51200 ]; then echo "    $(basename "$f"): over 51,200 bytes, skipped (needs an S3 URL)"; continue; fi
      if aws cloudformation validate-template --template-body "file://$f" >/dev/null 2>/tmp/kc-validate.err; then
        echo "    OK  $(basename "$f")"
      else echo "    FAIL $(basename "$f"): $(cat /tmp/kc-validate.err)"; ok=1; fi
    done
    return $ok
  }
  run "6 AWS validate-template (read-only)" validate
else skip "6 AWS validate-template" "no AWS credentials"; fi

pycheck() { python3 -m py_compile "$ROOT"/backend/api/app/*.py "$ROOT"/backend/api/app/routes/*.py "$ROOT"/backend/ingest/*.py "$ROOT"/agent/app/*.py; local rc=$?
  find "$ROOT" -name __pycache__ -not -path '*/node_modules/*' -exec rm -rf {} + 2>/dev/null; return $rc; }
run "7 python sources compile" pycheck

backend() {
  local py="${BACKEND_PYTHON:-python3}" rc=0
  (cd "$ROOT/backend" && "$py" -m ruff check . && "$py" -m ruff format --check . && "$py" -m pytest) || rc=1
  find "$ROOT/backend" -name __pycache__ -o -name .pytest_cache | xargs rm -rf 2>/dev/null
  return $rc
}
BACKEND_PY="${BACKEND_PYTHON:-python3}"
if "$BACKEND_PY" -c "import fastapi, moto, pytest" >/dev/null 2>&1 && "$BACKEND_PY" -m ruff --version >/dev/null 2>&1; then
  run "8 backend (ruff, pytest)" backend
else skip "8 backend" "dependencies missing: pip install -r backend/api/requirements.txt -r backend/requirements-dev.txt"; fi

printf '\n==================== SUMMARY ====================\n'
for r in "${RESULTS[@]}"; do printf '  %-8s %s\n' "${r#*|}" "${r%%|*}"; done
if [ "$FAILED" -ne 0 ]; then printf '\nVERIFY FAILED\n'; exit 1; fi
printf '\nVERIFY OK (layers marked SKIPPED did not run)\n'
