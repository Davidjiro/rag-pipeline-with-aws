"""Runtime configuration, read from environment variables set by the CDK (infra/lib/constructs/chat-agent-runtime.ts).

None of these values is a secret. AWS credentials come from the runtime's execution role.
"""

from __future__ import annotations

import os
from dataclasses import dataclass
from functools import lru_cache

# Fixed limits that protect cost and keep behaviour predictable.
# They are code, not configuration, so a deployment cannot lift them.
MAX_SEARCHES_PER_QUESTION = 3  # the model may refine its search, but not loop
MULTI_QUERY_COUNT = 3  # rewrites generated by the multi-query strategy (the original question is searched as well)
MAX_PASSAGE_CHARS = 1500  # passage text sent to the model; chunks are about 300 tokens, so this rarely cuts anything


@dataclass(frozen=True)
class Settings:
    region: str
    model_id: str
    knowledge_base_id: str
    guardrail_id: str
    guardrail_version: str
    top_k: int
    max_output_tokens: int
    min_score: float

    @classmethod
    def from_env(cls) -> Settings:
        """A missing required variable raises KeyError naming it."""
        env = os.environ
        return cls(
            region=env.get("AWS_REGION") or env.get("AWS_DEFAULT_REGION") or "us-east-1",
            model_id=env["MODEL_ID"],
            knowledge_base_id=env["KNOWLEDGE_BASE_ID"],
            guardrail_id=env["GUARDRAIL_ID"],
            guardrail_version=env["GUARDRAIL_VERSION"],
            top_k=int(env.get("TOP_K", "5")),
            max_output_tokens=int(env.get("MAX_OUTPUT_TOKENS", "1024")),
            # Passages scoring below this are dropped. 0 keeps everything. Not set by the CDK: tune it with a test set first.
            min_score=float(env.get("MIN_SCORE", "0")),
        )


@lru_cache
def get_settings() -> Settings:
    return Settings.from_env()
